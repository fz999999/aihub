const assert = require('node:assert/strict');
const s = require('./aihub-smart-group.user.js');
const future = new Date(Date.now() + 60000).toISOString();
const raw = { group_id: 1, platform: 'openai', code: 'test', available: true, rate_multiplier: 0.1, success_rates: { '10m': 1 }, group_models: [{ model: 'gpt-6-sol' }, { model: 'gpt-6.1-sol' }], model_cards: [{ model: 'gpt-6-sol', health: 'healthy', probe_state: 'enabled', health_expires_at: future }, { model: 'gpt-6.1-sol', health: 'failed' }] };
const row = s.normalizeMonitorRow(raw);
assert.deepEqual(row.groupModels, ['gpt-6-sol', 'gpt-6.1-sol']);
assert.equal(s.getRequiredModelsBlockReason(row, ['gpt-6-sol']), '');
assert.equal(s.getRequiredModelsBlockReason(row, ['gpt-6-sol', 'gpt-6.1-sol']), 'failed');
assert.equal(s.getRequiredModelsBlockReason(row, ['gpt-5.6-sol']), 'unsupported');
assert.equal(s.getRequiredModelsBlockReason({ ...row, modelCards: [] }, ['gpt-6-sol']), 'unknown');
assert.equal(s.getRequiredModelsBlockReason({ ...row, modelCards: [{ model: 'gpt-6-sol', health: 'healthy', expiresAt: '2000-01-01' }] }, ['gpt-6-sol']), 'stale');
assert.equal(s.getRequiredModelsBlockReason({ ...row, modelCards: [{ model: 'gpt-6-sol', health: 'healthy', probeState: 'disabled' }] }, ['gpt-6-sol']), 'unknown');
assert.equal(s.getRequiredModelsBlockReason({ ...row, modelCards: [{ model: 'gpt-6-sol', health: 'insufficient' }] }, ['gpt-6-sol']), 'unknown');
assert.equal(s.rankCandidates([row], { requiredModels: ['gpt-6-sol'] }).length, 1);
assert.equal(s.rankCandidates([row], { requiredModels: ['gpt-6.1-sol'] }).length, 0);
for (const mode of ['price', 'speed', 'balance']) assert.equal(s.rankCandidates([row], { mode, requiredModels: ['gpt-6.1-sol'] }).length, 0);
assert.notEqual(s.getRecommendationStrategySignature({ requiredModels: ['gpt-6-sol'] }), s.getRecommendationStrategySignature({ requiredModels: [] }));
const config = s.normalizeConfig({ requiredModels: ['gpt-6-sol'] });
const winner = s.rankCandidates([row], config)[0];
const stability = s.advanceStability(null, 1, 1, s.getRecommendationStrategySignature(config));
assert.ok(s.reanalyzeRecommendationForSwitch([{ ...row, modelCards: [] }], config, stability, winner.groupId).reason);
assert.equal(s.rankCandidates([{ ...row, modelCards: [] }], {}).length, 1);
// Legacy providers may publish healthy model cards without a group_models list.
const legacyRaw = { ...raw, group_id: 2, code: 'A018-like', rate_multiplier: 0.09 };
delete legacyRaw.group_models;
const legacy = s.normalizeMonitorRow(legacyRaw);
assert.equal(s.getRequiredModelsBlockReason(legacyRaw, ['gpt-6-sol']), '');
assert.equal(s.getRequiredModelsBlockReason(legacy, ['gpt-6-sol']), '');
assert.equal(s.getRequiredModelsBlockReason({ ...legacyRaw, group_models: [] }, ['gpt-6-sol']), 'unsupported');
assert.equal(s.getRequiredModelsBlockReason(legacy, ['gpt-6.1-sol']), 'failed');
assert.equal(s.getRequiredModelsBlockReason({ ...legacyRaw, model_cards: [] }, ['gpt-6-sol']), 'unsupported');
assert.equal(s.rankCandidates([row, legacy], config)[0].groupId, 2);
assert.equal(s.rankCandidates([legacy], { ...config, minOutputTokensPerSecond: 70 }).length, 0);
assert.equal(s.getGroupRecommendationDiagnostic({ ...legacy, outputTokensPerSecond: 48.7 }, { ...config, minOutputTokensPerSecond: 70 }).code, 'outputTpsLow');
assert.match(s.getGroupRecommendationDiagnostic({ ...legacy, outputTokensPerSecond: 48.7 }, { ...config, minOutputTokensPerSecond: 70 }).text, /70 tok\/s/);
assert.equal(s.getGroupRecommendationDiagnostic(legacy, { requiredModels: ['gpt-6.1-sol'] }).code, 'requiredModelExcluded:failed');
assert.equal(s.getGroupRecommendationDiagnostic(legacy, { availabilityMode: 'consecutive', minConsecutiveSuccesses10m: 2 }).code, 'lowSuccess');
assert.equal(s.getGroupRecommendationDiagnostic(legacy, { recommendationPriceBasis: 'effectiveInput1h' }).code, 'priceMetricUnavailable');
assert.equal(s.getGroupRecommendationDiagnostic(legacy, { mode: 'balance', balanceMaxPrice: 0.01 }).code, 'overLimit');
assert.equal(s.getGroupRecommendationDiagnostic(null, config).code, 'missing');
assert.equal(s.getGroupRecommendationDiagnostic(legacy, config).code, 'eligible');
assert.match(s.formatRecommendationDiagnosticMetrics(legacy, config), /标称倍率/);
const legacyStability = s.advanceStability(null, 2, 1, s.getRecommendationStrategySignature(config));
assert.equal(s.reanalyzeRecommendationForSwitch([row, legacy], config, legacyStability, 2).reason, '');
assert.ok(s.reanalyzeRecommendationForSwitch([{ ...legacy, modelCards: [] }], config, legacyStability, 2).reason);
console.log('PASS: model-list fallback, explicit empty-list exclusion, health guards, cheaper legacy provider ranking, switch revalidation and diagnostic reasons');
(async () => {
  const response = await fetch('https://aihub.dog/api/v1/public/providers?timezone=Asia%2FShanghai', { signal: AbortSignal.timeout(15000) });
  assert.ok(response.ok);
  const summary = s.normalizeMonitorSummaryPayload(await response.json());
  const model = 'gpt-6.1-sol';
  const analysis = s.analyzeCandidates(summary.apis, { requiredModels: [model], minSuccess10m: 0 });
  assert.ok(summary.apis.some(row => row.groupModels.includes(model)));
  assert.ok(analysis.candidates.every(row => !s.getRequiredModelsBlockReason(row, [model])));
  console.log(JSON.stringify({ liveGroups: summary.apis.length, requiredModel: model, eligible: analysis.candidates.length, modelExcluded: analysis.counts.requiredModelExcluded, reasons: analysis.counts.requiredModelReasons }));
})().catch(error => { console.error(error); process.exitCode = 1; });
